#!/usr/bin/env python3
"""Independent claim-evidence audit of the SGQR / CSGQR historical record.

This does NOT call the campaign's own ``verify_claims.py``. Every number quoted
in a committed document is re-derived here from the raw JSON artifact by code
written for this audit, so that a bug shared between the campaign's producer and
its verifier cannot hide.

Each row carries the fields the audit brief asks for: claim, algorithm, commit,
configuration, dataset, seed, raw artifact, derived metric, reproducibility
status, potential confound, confidence.

Status vocabulary
-----------------
VERIFIED                      the doc number re-derives from the committed raw
                              artifact by independent code, within tolerance
TRACEABLE_BUT_NOT_REPRODUCED  the artifact exists and supports the number, but
                              the number was not regenerated by re-running the
                              producing code in this audit
REPRODUCED                    re-run in this audit and agrees
AMBIGUOUS                     the artifact supports more than one reading, or
                              the doc is imprecise about which artifact it means
INVALID                       the artifact contradicts the doc
MISSING_PROVENANCE            no committed artifact backs the number
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "experiments/audit_sgqr_csgqr/results"
OUT.mkdir(parents=True, exist_ok=True)

_cache: dict[str, dict] = {}


def load(rel: str) -> dict:
    if rel not in _cache:
        _cache[rel] = json.loads((ROOT / rel).read_text(encoding="utf-8"))
    return _cache[rel]


def git(*a: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *a],
                          capture_output=True, text=True).stdout.strip()


def carrying_commit(rel: str) -> str:
    if not rel:
        return ""
    return git("log", "-1", "--format=%h", "--", rel) or "UNTRACKED"


def arm(fam: str, name: str) -> dict:
    return load("experiments/csgqr/results/" + fam + ".json")["arms"][name]


def pt(fam: str, name: str, metric: str) -> float:
    v = arm(fam, name)[metric]
    return v["point"] if isinstance(v, dict) else float(v)


def ci(fam: str, name: str, metric: str):
    v = arm(fam, name)[metric]
    return v["lo"], v["hi"]


def recovery(fam: str, name: str, delete_fam: str = None,
             delete_arm: str = "b1-delete") -> float:
    d = pt(delete_fam or fam, delete_arm, "kl")
    return 1.0 - pt(fam, name, "kl") / d


ROWS: list[dict] = []


def check(claim, algorithm, doc, artifact, expected, actual, tol=5e-4, *,
          config="", dataset="", seed="", metric="", confound="",
          status=None, note=""):
    if status is None:
        if actual is None:
            status = "MISSING_PROVENANCE"
        elif isinstance(expected, bool) or isinstance(actual, bool):
            status = "VERIFIED" if bool(expected) == bool(actual) else "INVALID"
        elif isinstance(expected, (list, tuple)) or isinstance(actual, (list, tuple)):
            status = "VERIFIED" if list(expected) == list(actual) else "INVALID"
        elif isinstance(expected, str):
            status = "VERIFIED" if str(expected) == str(actual) else "INVALID"
        else:
            ok = abs(float(actual) - float(expected)) <= tol
            status = "VERIFIED" if ok else "INVALID"
    ROWS.append({
        "claim": claim, "algorithm": algorithm, "doc": doc,
        "artifact": artifact, "artifact_commit": carrying_commit(artifact),
        "config": config, "dataset": dataset, "seed": seed,
        "derived_metric": metric, "doc_value": expected, "audit_value": actual,
        "tolerance": tol, "status": status, "confound": confound, "note": note,
    })


def dig(d, *keys, default=None):
    for k in keys:
        if isinstance(d, dict) and k in d:
            d = d[k]
        else:
            return default
    return d


