def frontier(prefix: str):
    out = []
    for k, v in load(PE)["arms"].items():
        if k.startswith(prefix):
            out.append((v["routing"]["active_fraction"], v["kl"]["point"]))
    return sorted(out)


def interp(curve, x):
    for (x0, y0), (x1, y1) in zip(curve, curve[1:]):
        if x0 <= x <= x1:
            return y0 if x1 == x0 else y0 + (y1 - y0) * (x - x0) / (x1 - x0)
    return None


