#!/usr/bin/env python3
"""Collect results/ into one findings table.

Reports, for every run, how much of the budget was actually chosen *by
significance* as opposed to occupied by the fixed sinks+recent regions. Without
that column the sweep is easy to misread: at a small budget the recent window
consumes almost the whole allowance and the run is really StreamingLLM wearing a
significance badge, so a good score there is not evidence that scoring works.

Usage:
    python src/summarize.py
"""

from __future__ import annotations

import argparse
import json
import statistics
import time
from pathlib import Path

EXP = Path(__file__).resolve().parents[1]
RES = EXP / "results"


def sig_share(man: dict, rows: list[dict]) -> float:
    """Fraction of the kept budget selected by score rather than by position."""
    if not man.get("eviction"):
        return float("nan")
    sinks, recent = man.get("sinks", 0), man.get("recent", 0)
    shares = []
    for r in rows:
        b = r.get("stored_kv") or 0
        if b <= 0:
            continue
        s = min(sinks, b)
        rec = min(recent, max(0, b - s))
        shares.append(max(0, b - s - rec) / b)
    return statistics.mean(shares) if shares else float("nan")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=RES / "FINDINGS.md")
    args = ap.parse_args()

    runs = sorted(p for p in RES.glob("*__*") if (p / "summary.json").exists())
    by_ds: dict[str, list] = {}
    for run in runs:
        tag, _, ds = run.name.partition("__")
        man = json.loads((run / "run_manifest.json").read_text(encoding="utf-8")) \
            if (run / "run_manifest.json").exists() else {}
        summ = json.loads((run / "summary.json").read_text(encoding="utf-8"))
        rows = [json.loads(l) for l in
                (run / "results.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
        by_ds.setdefault(ds, []).append((tag, man, summ, rows, run))

    lines = ["# Significance-gated eviction — findings", "",
             "Generated by `src/summarize.py`. Do not edit by hand; rerun it.", ""]

    conc = RES / "concentration.json"
    if conc.exists():
        c = json.loads(conc.read_text(encoding="utf-8"))
        lines += ["## Phase 0 — attention concentration", "",
                  f"{c['cases']} prompts, seq {c['seq_len_min']}–{c['seq_len_max']}, "
                  f"observation window {c['last_queries']}.", "",
                  "| budget k | rho(k) | rho(k) sinks removed | error bound 2(1-rho)V |",
                  "|---:|---:|---:|---:|"]
        for k, r, rn in zip(c["ks"], c["rho_mean"], c["rho_nosink_mean"]):
            lines.append(f"| {k} | {r:.3f} | {rn:.3f} | {2*(1-r):.3f} |")
        lines.append("")

    for ds, entries in sorted(by_ds.items()):
        ref = next((e for e in entries if e[0] == "off"), None)
        lines += [f"## {ds}", "",
                  "| run | keep | mean quality | vs off | identical | kept/prompt | "
                  "significance-selected |",
                  "|---|---|---:|---:|---|---:|---:|"]
        ref_rows = {r["id"]: r for r in ref[3]} if ref else {}
        ref_q = ref[2]["mean_quality_score"] if ref else None
        order = sorted(entries, key=lambda e: (e[0] != "off", e[0]))
        for tag, man, summ, rows, _ in order:
            q = summ["mean_quality_score"]
            delta = f"{q - ref_q:+.5f}" if ref_q is not None and tag != "off" else "—"
            if ref_rows and tag != "off":
                common = [r for r in rows if r["id"] in ref_rows]
                same = sum(1 for r in common if r["reply"] == ref_rows[r["id"]]["reply"])
                ident = f"{same}/{len(common)}"
            else:
                ident = "—"
            keep = man.get("keep_frac")
            keep_s = f"{keep:.2f}" if keep is not None else ("off" if not man.get("eviction")
                                                            else str(man.get("budget")))
            share = sig_share(man, rows)
            share_s = "—" if share != share else f"{share:.0%}"
            pool = man.get("pool", 1)
            name = tag + (" (pooled)" if pool and pool > 1 else "")
            lines.append(f"| `{name}` | {keep_s} | {q:.5f} | {delta} | {ident} | "
                         f"{man.get('mean_kept_ratio', float('nan')):.3f} | {share_s} |")
        lines.append("")

    lines += ["", f"_generated {time.strftime('%Y-%m-%d %H:%M')}_"]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
